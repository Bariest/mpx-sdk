void on_start(void)
{
    MPX_LOG("dance_3: start\n");
    robot_set_config(160, 70, 10, 10, 10);   /* period > 150 */
    robot_gait((int)"init");
    robot_delay_ms(2000);
    for (int i = 0; i < 239; i++) {
        if (BEATS[i].wait_ms) robot_delay_ms(BEATS[i].wait_ms * 2);
        robot_gait((int)MOVES[BEATS[i].m]);
        robot_delay_ms(HOLD_MS);
        robot_gait((int)"none");
    }
    robot_delay_ms(800);
    robot_gait((int)"init");
    robot_delay_ms(1500);
    robot_gait((int)"none");
    MPX_LOG("dance_3: done\n");
}
